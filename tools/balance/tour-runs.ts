const args = process.argv.slice(2);
const opt = (k: string, d: string) => {
  const i = args.indexOf(`--${k}`);
  return i < 0 ? d : args[i + 1];
};
const N = Number(opt("n", "2000"));
const PLAYER = opt("player", "good") as PlayerProfileId;
const OUT = opt("out", "");

const pack = JSON.parse(readFileSync("public/packs/enztal/pack.json", "utf8")) as PlacePack;
const profile = JSON.parse(readFileSync("public/profile.default.json", "utf8")) as Profile;

// Events: the Text area's decks when they exist, else the Tour fixture.
async function loadEvents(): Promise<{ events: EventDef[]; source: string; problems: string[] }> {
  try {
    if (readdirSync("src/content/events").includes("index.ts")) {
      const m = (await import("../../src/content/events/index.ts")) as { ALL_EVENTS?: EventDef[] };
      const evs = m.ALL_EVENTS ?? [];
      if (evs.length >= 20) return { events: evs, source: `src/content/events (${evs.length} events)`, problems: validateEvents(evs) };
      return { events: FIXTURE_EVENTS, source: `Tour fixture (${FIXTURE_EVENTS.length} events; src/content/events has only ${evs.length})`, problems: validateEvents(evs) };
    }
  } catch (e) {
    return { events: FIXTURE_EVENTS, source: `Tour fixture (content failed to load: ${String(e).split("\n")[0]})`, problems: [] };
  }
  return { events: FIXTURE_EVENTS, source: `Tour fixture (${FIXTURE_EVENTS.length} events)`, problems: [] };
}

const { events, source, problems } = await loadEvents();

const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)} %` : "–");
const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const q = (xs: number[], p: number) => {
  if (!xs.length) return 0;
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor(p * s.length))];
};
const f1 = (x: number) => x.toFixed(1);

function runs(difficulty: DifficultyId, n: number, player: PlayerProfileId): SimReport[] {
  const skat = stubSkatModel({ player: PLAYER_PROFILES[player] });
  const out: SimReport[] = [];
  for (let i = 1; i <= n; i++) out.push(simulateTour({ seed: i * 7919 + 13, difficulty, pack, profile, events, skat }));
  return out;
}

